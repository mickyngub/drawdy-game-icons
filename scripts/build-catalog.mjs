import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CATEGORIES, MATCH_ORDER, SYNONYMS } from "./game-categories.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "catalog-data.ts");
const PREFIX = "game-icons";

const readPackage = (file) =>
    JSON.parse(
        readFileSync(
            join(ROOT, "node_modules", "@iconify-json", PREFIX, file),
            "utf8"
        )
    );

export function titleFor(name) {
    const text = name.split("-").join(" ");
    return text.charAt(0).toUpperCase() + text.slice(1);
}

// "hot-dog" matches the name "hot-dog" and "hot-dog-stand", not "hot-dogs".
export function hasWord(name, word) {
    return `-${name}-`.includes(`-${word}-`);
}

export function categoryOf(name) {
    for (const id of MATCH_ORDER) {
        const group = CATEGORIES.find((entry) => entry.id === id);
        if (group.words.some((word) => hasWord(name, word))) return id;
    }
    return null;
}

function keywordsFor(name, category) {
    const words = [];
    if (category !== null) {
        const group = CATEGORIES.find((entry) => entry.id === category);
        words.push(group.title.toLowerCase().replace(/ & /g, " "));
        if (group.keywords) words.push(group.keywords);
    }
    for (const rule of SYNONYMS) {
        if (rule.words.some((word) => hasWord(name, word))) {
            words.push(rule.keywords);
        }
    }
    return words.join(" ");
}

const byTitle = (a, b) => (a.title < b.title ? -1 : a.title > b.title ? 1 : 0);

export function buildCatalog(data) {
    const icons = [];
    const members = new Map(CATEGORIES.map((group) => [group.id, []]));
    for (const [name, icon] of Object.entries(data.icons)) {
        if (icon.hidden) continue;
        const category = categoryOf(name);
        const entry = {
            name,
            title: titleFor(name),
            keywords: keywordsFor(name, category),
        };
        icons.push(entry);
        if (category !== null) members.get(category).push(entry);
    }
    icons.sort(byTitle);
    const categories = CATEGORIES.map((group) => ({
        id: group.id,
        title: group.title,
        names: members
            .get(group.id)
            .sort(byTitle)
            .map((entry) => entry.name),
    }));
    return { icons, categories };
}

function source(catalog) {
    const version = readPackage("package.json").version;
    return (
        `// Generated by scripts/build-catalog.mjs from @iconify-json/${PREFIX} ${version} and scripts/game-categories.mjs. Do not edit by hand.\n` +
        `import type { CatalogIcon, Category } from "./catalog";\n\n` +
        `export const ICONS: CatalogIcon[] = ${JSON.stringify(catalog.icons)};\n\n` +
        `export const CATEGORIES: Category[] = ${JSON.stringify(catalog.categories)};\n`
    );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const text = source(buildCatalog(readPackage("icons.json")));
    // Skipping identical writes keeps a second build from dirtying the tree.
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
        writeFileSync(OUT, text);
    }
}
